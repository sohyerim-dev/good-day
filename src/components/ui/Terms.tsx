"use client";

import Modal from "@/components/ui/Modal";
import { useState } from "react";

interface TermsProps {
  id: string;
  label: string;
  className?: string;
  modal?: boolean;
  checked: boolean;
  onClick: () => void;
  onChange: () => void;
}
export default function Terms({
  id,
  label,
  className,
  modal,
  checked,
  onClick,
  onChange,
}: TermsProps) {
  const [showModal, setShowModal] = useState(false);

  function handleModal(id: string) {
    if (id === "privacy")
      return (
        <Modal title="개인정보처리방침" onClose={() => setShowModal(false)}>
          {PRIVACY_POLICY}
        </Modal>
      );
    return (
      <Modal title="이용약관" onClose={() => setShowModal(false)}>
        {TERMS_OF_SERVICE}
      </Modal>
    );
  }
  return (
    <>
      <div className={className}>
        <input
          type="checkbox"
          checked={checked}
          id={id}
          className="mr-2.5"
          onClick={onClick}
          onChange={onChange}
        />
        <label htmlFor={id} className="mr-2.5">
          {label}
        </label>
        {modal ? (
          <button
            type="button"
            className="underline cursor-pointer text-blue-700"
            onClick={() => setShowModal(true)}
          >
            보기
          </button>
        ) : (
          ""
        )}
      </div>
      {showModal && handleModal(id)}
    </>
  );
}

